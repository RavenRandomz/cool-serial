# Bytes literal 101 (please correct if I'm wrong) :

# 0x is the standard prefix for the Python parser
# EXAMPLE: >>> 0x84 will display 132

# \x (escape sequence x) is the standard prefix for bytes literal
# EXAMPLE: >>> b'/x48' will display 'H'

# They are technically the same since machine only reads binary (0s & 1s)
# However, note that the MCB only expects bytes literal prefix (\x)